#!/usr/bin/env python3
"""Generate docs/CLEANERS.md (every cleaner, path and rating) from the JSON registry.

Paths are shown with a placeholder home so the output does not depend on who runs it.
"""

import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)


def main() -> int:
    fake_home = tempfile.mkdtemp(prefix="jc-docs-")
    os.environ["HOME"] = fake_home
    os.environ["USER"] = "user"
    for v in ("XDG_CONFIG_HOME", "XDG_CACHE_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME",
              "HF_HOME", "HF_HUB_CACHE", "GOPATH", "GOCACHE", "GOMODCACHE"):
        os.environ.pop(v, None)
    from headroom.core import registry

    reg = registry.load_registry(registry.default_data_dir(), custom_dir="", discover=False, strict=True)

    def short(p: str) -> str:
        p = p.replace(fake_home, "~").replace(f"/{os.getuid()}", "/$UID")
        p = p.replace(f"-{os.getuid()}", "-$UID")
        return p.replace("|", "\\|")

    out = ["# Cleaner reference", "",
           "Generated by `scripts/gen_cleaner_docs.py` from `data/cleaners/*.json` — do not edit by hand.",
           "", "Ratings: **S** Safe (regenerable) · **C** Caution (side effects) · "
           "**A** Advanced (possible data loss; hidden by default, never pre-selected). "
           "Root = system helper via pkexec.", ""]
    for cat in registry.CATEGORIES:
        cleaners = [c for c in reg.cleaners if c.category == cat]
        if not cleaners:
            continue
        out += [f"## {cat}", "", "| App | Option | Rating | Root | Method | Paths / command |",
                "|---|---|---|---|---|---|"]
        for c in cleaners:
            for o in c.options:
                what = []
                if o.command:
                    from headroom.core.commands import COMMANDS
                    spec = COMMANDS[o.command]
                    what.append("`" + " ".join((spec.tools[0], *spec.args)) + "`" +
                                ("" if o.command_only else " (else delete)"))
                if o.root_action:
                    what.append(f"helper action `{o.root_action['id']}`")
                elif o.root_fallback:
                    what.append(f"(root fallback `{o.root_fallback['id']}`)")
                paths = [f"{t.mode}: `{short(t.path)}`" for t in o.targets]
                if len(paths) > 6:
                    paths = paths[:6] + [f"… +{len(o.targets) - 6} more"]
                what += paths
                what += [f"report: `{short(p)}`" for p in o.probe_paths[:3]] if o.report_only else []
                method = "report only" if o.report_only else o.method
                out.append(f"| {c.label} | {o.label} | {o.rating[0].upper()} | "
                           f"{'yes' if o.root or o.root_action else ''} | {method} | {'<br>'.join(what)} |")
        out.append("")
    out += ["## Never touched", "",
            "The deny-list in `headroom/core/paths.py` always wins: `/`, `$HOME`, `~/.ssh`, `~/.gnupg`, "
            "`~/.local/share/keyrings`, `~/.mozilla`, `~/snap/firefox/common/.mozilla`, "
            "`~/.config/*/User/{settings.json,keybindings.json,snippets,profiles,globalStorage}` "
            "(except `state.vscdb.backup`), `~/.vscode-shared`, `~/.password-store`, `~/Documents`, "
            "`~/Pictures`, `~/Desktop`, `/etc`, `/usr`, `/boot`, `/var/lib/dpkg`, `/var/lib/docker`, "
            "`/var/cache/debconf` and every mount point.", ""]
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "CLEANERS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote docs/CLEANERS.md ({sum(len(c.options) for c in reg.cleaners)} options)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
